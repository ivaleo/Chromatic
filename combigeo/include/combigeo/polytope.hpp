#pragma once
// Ячейка Вороного решётки: H-представление (релевантные полупространства),
// V-представление (вершины), f-вектор, диаметр.
//
// Алгоритм построения (теорема Вороного о релевантных векторах):
// 0) Масштабная нормировка: базис приводится к масштабу det^(1/n) ~ 1
//    (результат возвращается в исходных единицах) — допуски осмысленны при
//    любом масштабе входа.
// 1) Релевантные векторы — СЕРТИФИЦИРОВАННО: для каждого из 2^n - 1 ненулевых
//    классов смежности Λ/2Λ минимумы класса находятся точным CVP-перебором
//    (сдвинутый sphere decoding по 2Λ со стартовым радиусом Бабаи).
//    Класс релевантен ⟺ минимум единственный с точностью до знака (±v);
//    тогда биссектор x·v <= |v|^2/2 — фасета ячейки.
// 2) Вершины: перебор всех комбинаций n фасет, решение СЛАУ, фильтр по всем
//    неравенствам (с допуском), дедупликация.
// 3) Фасеты, чьи инцидентные вершины не порождают гиперплоскость (аффинный
//    ранг < n-1), отбрасываются.
// 4) f-вектор: комбинаторное перечисление граней по инцидентности вершина-фасета
//    (замыкание: грань = множество вершин, общих для набора фасет).
// 5) Self-check: центральная симметрия вершин и соотношение Эйлера;
//    при нарушении — std::runtime_error (вместо тихо неверной ячейки).

#include <vector>

#include "combigeo/lattice.hpp"
#include "combigeo/linalg.hpp"

namespace combigeo {

// Полупространство x·normal <= offset; normal — ЕДИНИЧНОЙ длины.
struct Halfspace {
    Vec normal;
    double offset = 0.0;
    Vec lattice_vector;  // исходный вектор решётки v (фасета — биссектор v)
};

struct VoronoiCell {
    int dim = 0;
    std::vector<Vec> vertices;        // вершины ячейки
    std::vector<Halfspace> facets;    // релевантные фасеты
    double diameter = 0.0;            // 2 * max|вершина| (ячейка центрально-симметрична)
    std::vector<long> f_vector;       // [f_0, f_1, ..., f_{n-1}]: вершины, рёбра, ..., фасеты

    // инцидентность: для каждой вершины — отсортированные индексы содержащих её фасет
    std::vector<std::vector<int>> vertex_facets;

    // точка внутри ячейки (включая границу с допуском tol)?
    bool contains(const Vec& p, double tol = 1e-9) const;
};

// Строит ячейку Вороного центральной точки решётки.
// window — УСТАРЕЛ и игнорируется (сохранён для совместимости сигнатуры):
// релевантные векторы ищутся сертифицированным CVP-перебором без окон.
//
// Практический предел размерности. Шаг построения вершин перебирает все наборы
// из n фасет среди m релевантных — это O(C(m, n)) решений СЛАУ; для решёток с
// большим m (до 2(2^n - 1)) рост комбинаторный: n = 2..5 практичны
// (A5*-пермутоэдр, m = 62 — секунды), n = 6 для генерических решёток
// (m = 126) вне досягаемости этого алгоритма перебора вершин.
VoronoiCell build_voronoi_cell(const Lattice& lat, int window = 3);

// Только релевантные ФАСЕТЫ (опорные полупространства) центральной ячейки ---
// БЕЗ перечисления вершин. Работает в любой размерности (n = 6..8 практичны):
// стоимость — 2^n - 1 классов смежности × CVP-перебор. Масштабная нормировка
// входа включена; фасеты возвращаются в исходных единицах. Нужна для больших
// размерностей, где перебор вершинами (build_voronoi_cell) неосуществим.
std::vector<Halfspace> relevant_facets(const Lattice& lat);

}  // namespace combigeo
