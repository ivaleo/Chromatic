#pragma once
// Расстояние от точки до выпуклого многогранника, заданного вершинами.
// Алгоритм GJK (Гилберта–Джонсона–Кирти), размерность-независимый:
// итеративно строит симплекс из вершин-носителей; ближайшая точка симплекса
// ищется перебором его подсимплексов с решением нормальных уравнений
// (надёжный вариант для малых размерностей, без хрупких знаковых объёмов).
//
// Этот модуль — замена каскада проекций по граням: не требует комбинаторики
// граней вообще и не страдает от ошибок ориентации нормалей.

#include <vector>

#include "combigeo/linalg.hpp"

namespace combigeo {

struct GjkResult {
    double distance = 0.0;  // расстояние от точки до многогранника (0 — внутри)
    Vec closest;            // ближайшая точка многогранника
    int iterations = 0;
    // Сертификат оптимальности: гарантированная верхняя оценка ошибки
    // |distance - dist(p, P)| по зазору двойственности (distance всегда >= истинного,
    // т.к. closest ∈ P; error вычисляется финальным опорным проходом на ЛЮБОМ пути
    // выхода). 0 для точек внутри многогранника.
    double error = 0.0;
};

// Расстояние от точки p до conv(vertices). vertices непусто.
// tol — относительный допуск сходимости; max_iter — предохранитель.
GjkResult distance_to_polytope(const Vec& p, const std::vector<Vec>& vertices,
                               double tol = 1e-12, int max_iter = 200);

// Ближайшая к p точка симплекса conv(simplex) (перебор подсимплексов,
// решение нормальных уравнений). Используется внутри GJK; выделена в API
// для тестируемости. simplex: 1..dim+1 аффинно независимых точек
// (при зависимости лишние члены подсимплексов отбрасываются по вырожденности СЛАУ).
// ВНИМАНИЕ: валидации входа нет. На пустом симплексе функция возвращает пустой
// Vec (в debug сработает assert внутри проекции); размерности точек simplex и p
// считаются согласованными — вызывающая сторона обязана это обеспечить.
Vec closest_point_on_simplex(const Vec& p, const std::vector<Vec>& simplex);

}  // namespace combigeo
